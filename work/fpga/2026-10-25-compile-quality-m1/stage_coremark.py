def freeze():
    protect();arts=read(H/'build-result.json')['artifacts'];targets=[];cases={}
    assert len(arts)==2
    for a in arts:
        tid=a['id']+'-N234';d=H/'cases'/tid/'source';d.mkdir(parents=True)
        for f in (H/'source').iterdir():shutil.copyfile(f,d/f.name)
        image=(H/'build'/a['id']/'program.bin').read_bytes();assert len(image)%4==0
        lib.table([int.from_bytes(image[i:i+4],'little') for i in range(0,len(image),4)]+[0]*((32768-len(image))//4),[0xa5a5a5a5]*8192,d/'init_tables.svh')
        # Independently roundtrip complete ROM/RAM from the emitted init table.
        for k,expected in [('ROM',image+bytes(32768-len(image))),('RAM',b'\xa5'*32768)]:
            body=re.search(rf'{k}_BITS\s*=\s*\{{(.*?)\}};', (d/'init_tables.svh').read_text(),re.S)[1]
            assert int(''.join(re.findall(r"4096'h([0-9a-fA-F]+)",body)),16).to_bytes(32768,'little')==expected
        phase=a['symbols']['timing_phase'];out=H/'compile'/(tid+'.vvp')
        argv=[lib.IVL,'-B',lib.LIB,'-g2012','-Wall','-DM0_VERIFY','-I',d,'-I',M/'verification','-s','tb_board_coremark',f'-Ptb_board_coremark.PHASE_ADDR={phase}','-o',out,*list(d.glob('*.v')),*list(d.glob('*.sv')),H/'tests/tb_board_coremark.sv',lib.VENDOR/'GTP_DRM18K_E1.v',lib.VENDOR/'GTP_GRS.v']
        targets.append(dict(id=tid,argv=list(map(str,argv)),output=str(out)))
        cases[tid]=dict(old_run=str(B/'runs'/tid),phase_address=phase,INIT_sha256=sha(d/'init_tables.svh'),bin_sha256=a['bin_sha'],n=234)
