        d=H/'build'/name;d.mkdir();art=next(a for a in old['artifacts'] if a['id']==name);records=[]
        for i,r in enumerate(art['commands']):
            argv=[x.replace(str(T),str(H)) for x in r['argv']]
            if i==0:
                assert argv.count('-O2')==1;argv[argv.index('-O2')]='-O3'
            kind=['compile','objcopy','objdump','readelf','undefined'][i]
            out=bounded(argv,d,'build-'+name+'-'+kind,60 if i==0 else 20);records.append(out)
            if out['returncode'] or out['timed_out'] or out['cap']:
                save(H/'build-result.json',dict(status='STOPPED',program=name,commands=records,artifacts=rows));raise RuntimeError('GCC candidate failed; no retry/RTL expansion')
        image=(d/'program.bin').read_bytes();symbols=elf.elf_symbols(d/'program.elf');raw=(d/'program.elf').read_bytes()
