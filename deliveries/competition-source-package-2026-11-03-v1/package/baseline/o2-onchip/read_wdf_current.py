"""Limited reader for our one-core 140-channel/1024-point PDS WDF captures.

Not a general WDF implementation. Validate against native-exported VCD/CSV.
"""
from pathlib import Path
import re,csv,json,hashlib
WIDTHS=[('soc/cpu_core/id_pc',32),('soc/cpu_core/id_valid',1),('soc/cpu_core/pipeline_advance',1),('soc/cpu_core/eei_hold',1),('soc/cpu_core/stall_if',1),('soc/cpu_core/flush_id',1),('soc/cpu_core/branch_taken',1),('sys_rst_n',1),('soc/timer_ticks',32),('soc/address',32),('soc/wren',1),('soc/wdata',32),('stopped',1),('stop_kind',2),('write_error',1)]
FIC_SHA='F932FE45950D7B3CF1513404DF4794970490E76070C85270E750977934CC4B06'
def decode(raw,fic):
 if len(raw)<4 or int.from_bytes(raw[:4],'big')!=len(raw)-4:raise ValueError('WDF outer size mismatch/truncation')
 if hashlib.sha256(fic).hexdigest().upper()!=FIC_SHA:raise ValueError('Unknown probe mapping')
 text=fic.decode('utf8');channels=dict((int(a),b.strip()) for a,b in re.findall(r'^Project\.unit<0>\.dataChannel<(\d+)>=(.*)$',text,re.M))
 # Files generated by this PDS build declare dataChannel<port><index> instead.
 if not channels:channels=dict((int(a),b.strip()) for a,b in re.findall(r'^Project\.unit<0>\.dataChannel<0><(\d+)>=(.*)$',text,re.M))
 if not channels and 'Project.unit<0>.dataEqualsTrigger=true' in text:channels=dict((int(a),b.strip()) for a,b in re.findall(r'^Project\.unit<0>\.triggerChannel<0><(\d+)>=(.*)$',text,re.M))
 expected=[]
 for name,width in WIDTHS:expected.extend([name+f'[{i}]' if width>1 else name for i in range(width)])
 if len(channels)!=140 or [channels[i] for i in range(140)]!=expected:raise ValueError('FIC order differs')
 pat=re.compile(rb'\x00\x00\x08\x00((?:\x00[01xXzZ]){1024})')
 matches=list(pat.finditer(raw))
 if len(matches)!=140:raise ValueError('Expected exactly140 length-prefixed1024-point signal planes; unsupported content')
 planes=[m.group(1).decode('utf-16be') for m in matches]
 if any(c not in '01' for s in planes for c in s):raise ValueError('X/Z in capture; not accepted as binary state')
 rows=[]
 for sample in range(1024):
  row={'sample':sample};offset=0
  for name,width in WIDTHS:
   row[name]=sum((planes[offset+j][sample]=='1')<<j for j in range(width));offset+=width
  rows.append(row)
 return rows
def summary(rows):
 out={}
 for name,width in WIDTHS:
  values=[r[name] for r in rows];out[name]={'width':width,'initial':values[0],'final':values[-1],'unique':len(set(values)),'transitions':sum(a!=b for a,b in zip(values,values[1:]))}
 ticks=[r['soc/timer_ticks'] for r in rows]
 return {'samples':len(rows),'channels':140,'signals':out,'timer_adjacent_delta_mod32':sorted(set((b-a)&0xffffffff for a,b in zip(ticks,ticks[1:]))),'limits':['One-core140-bit/1024-point binary WDF subset only','No true retirement PC; pipeline_advance is not retirement','No UART physical-link or CoreMark CRC proof from stopped PC alone','No physical clock frequency inferred from export/display timescale']}
